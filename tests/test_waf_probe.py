@pytest.mark.anyio
async def test_waf_probe_medium_with_network_error_part(monkeypatch):
    """Baseline reachable + a bot-level exception (below the critical
    threshold) must render MEDIUM that counts network errors separately —
    honest partial evidence, not accusation, not silence."""
    flaky_ua = list(WAFProbeEngine.AI_CRAWLER_USER_AGENTS.values())[0]

    class OkResp:
        status_code = 200
        text = "<html><body><h1>Welcome</h1></body></html>"
        headers = {}

    async def mock_mixed(*args, **kwargs):
        ua = (kwargs.get("headers") or {}).get("User-Agent", "")
        if ua == flaky_ua:
            raise ConnectionError("one unlucky bot timed out")
        return OkResp()

    import httpx
    monkeypatch.setattr(httpx.AsyncClient, "get", mock_mixed)
    res = await WAFProbeEngine.probe_url("https://flakysite.com")
    assert res.baseline_reachable is True
    assert res.overall_risk == WAFRiskLevel.MEDIUM
    assert res.unreachable_bots_count == 1
    assert res.blocked_bots_count == 1  # browser-OK + bot-drop = genuine silent block (below critical threshold)
    assert res.is_silently_blocked is True
    assert "ağ hatası verdi" in res.remediation_recommendation
    assert "engellendi" in res.remediation_recommendation
