@pytest.mark.anyio
async def test_waf_probe_target_unreachable_is_unverified(monkeypatch):
    """If even the baseline browser request cannot connect, the probe must NOT
    accuse the site of WAF blocking — it returns UNVERIFIED with zero blocks."""
    async def mock_boom(*args, **kwargs):
        raise TimeoutError("connection timed out after 6s")
    import httpx
    monkeypatch.setattr(httpx.AsyncClient, "get", mock_boom)
    res = await WAFProbeEngine.probe_url("https://unreachable.example")
    roster = len(WAFProbeEngine.AI_CRAWLER_USER_AGENTS)
    assert res.overall_risk == WAFRiskLevel.UNVERIFIED
    assert res.is_silently_blocked is False
    assert res.blocked_bots_count == 0
    assert res.unreachable_bots_count == roster
    assert res.baseline_reachable is False
    assert all(s.status_code == 0 for s in res.bot_statuses)
    assert all("Connection/Timeout Error" in (s.blocking_signature or "") for s in res.bot_statuses)
    assert "hüküm veremedi" in res.remediation_recommendation


@pytest.mark.anyio
async def test_waf_probe_silent_drop_while_browser_ok_is_critical(monkeypatch):
    """Baseline browser gets 200 but every bot UA connection is dropped -> the
    original 'silent blocking' detection must still fire CRITICAL."""
    async def mock_drop(*args, **kwargs):
        ua = (kwargs.get("headers") or {}).get("User-Agent", "")
        if "Chrome/120.0.0.0" in ua:  # baseline browser request
            class MockResp:
                status_code = 200
                text = "<html><body>ok</body></html>"
                headers = {}
            return MockResp()
        raise ConnectionResetError("connection reset by peer")
    import httpx
    monkeypatch.setattr(httpx.AsyncClient, "get", mock_drop)
    res = await WAFProbeEngine.probe_url("https://silent-drop.example")
    roster = len(WAFProbeEngine.AI_CRAWLER_USER_AGENTS)
    assert res.overall_risk == WAFRiskLevel.CRITICAL
    assert res.is_silently_blocked is True
    assert res.blocked_bots_count == roster
    assert res.unreachable_bots_count == roster  # dropped at connection level
    assert res.baseline_reachable is True
    assert all("Silent connection drop" in (s.blocking_signature or "") for s in res.bot_statuses)


